import logging
from typing import Any

from langchain.agents import AgentExecutor, create_tool_calling_agent
from langchain.tools import Tool
from langchain_core.prompts import ChatPromptTemplate
from langchain_groq import ChatGroq

from config import GROQ_API_KEY
from tools.wikipedia import wikipedia_tool
from tools.private_rag import rag_search_structured


logger = logging.getLogger(__name__)


# =================================================
# GROQ LLM
# =================================================

llm = ChatGroq(
    model="openai/gpt-oss-20b",
    temperature=0,
    api_key=GROQ_API_KEY,
)


# =================================================
# WIKIPEDIA
# =================================================

def wikipedia_search(query: str) -> str:
    """Search Wikipedia for public knowledge."""
    try:
        result = wikipedia_tool(query)

        if isinstance(result, dict):
            return str(
                result.get("content")
                or "No Wikipedia result found."
            )

        return str(result)

    except Exception:
        logger.exception("Wikipedia tool failed")
        return "Wikipedia search failed. Please try again."


# =================================================
# PRIVATE RAG RESULT FORMATTER
# =================================================

def format_rag_result(
    query: str,
    result: dict[str, Any],
) -> str:
    """Format structured RAG data for the LangChain agent."""

    answer = result.get("answer", "No answer was returned.")
    sources = result.get("source") or []
    status = result.get("status", "unknown")
    error = result.get("error")

    if status == "sources_found":
        return (
            "PRIVATE RAG RESULTS\n"
            "Status: Document sources were returned.\n"
            "The answer was generated by Domain B using its "
            "retrieval workflow. Check source relevance before "
            "attributing individual claims to documents.\n\n"
            f"Question: {query}\n"
            f"Answer: {answer}\n"
            f"Sources: {sources}"
        )

    if status == "unverified":
        return (
            "PRIVATE RAG RESULTS\n"
            "Status: NO PRIVATE DOCUMENT SOURCES WERE RETURNED.\n"
            "IMPORTANT: The answer below is NOT verified by "
            "retrieved private documents. Domain B may have "
            "generated it using general LLM knowledge.\n\n"
            f"Question: {query}\n"
            f"Unverified answer: {answer}\n\n"
            "Instructions for the agent: Do not present this answer "
            "as a fact from internal documents. If appropriate, use "
            "Wikipedia to investigate the question independently, "
            "or tell the user that no supporting private sources "
            "were returned."
        )

    if error == "timeout":
        return (
            "PRIVATE RAG ERROR: The request timed out. "
            "No verified result was obtained from Domain B."
        )

    if error == "server_error":
        return (
            "PRIVATE RAG ERROR: Domain B returned a server error. "
            "No verified result was obtained."
        )

    if error == "request_failed":
        return (
            "PRIVATE RAG ERROR: Domain B is unavailable or the "
            "request failed. No verified result was obtained."
        )

    return (
        "PRIVATE RAG ERROR: The tool could not complete the "
        "request. Check the server configuration and logs."
    )


# =================================================
# PROMPT
# =================================================

prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """
You are an agentic RAG assistant with two tools:

1. Wikipedia: public information.
2. Private_RAG: the private knowledge result retrieved from Domain B.

TOOL SELECTION:
- ALWAYS call Private_RAG before answering any user question.
- Inspect its result before answering.
- Use Wikipedia when additional public information is useful.
- Use both tools when both private and public knowledge are needed.
- Do not invent internal documents, sources, or citations.

PRIVATE RAG SOURCE RULES:
- If document sources are returned, use them as evidence when relevant.
- Do not assume every claim in the RAG answer is supported by its sources.
- If no private document sources were returned, explicitly say so.
- Never present an answer without sources as verified private knowledge.
- Public information does not verify private organizational facts.
- Preserve relevant source references returned by Private_RAG.

ERROR HANDLING:
- If Private_RAG fails, explain that the private knowledge base
  could not be queried successfully.
- Never claim a tool succeeded when it failed.
- Wikipedia can provide useful public facts, but it cannot replace
  private evidence.

FINAL ANSWERS:
- Clearly distinguish private document evidence from public knowledge.
- Explain when no private document sources were returned.
- Be accurate, concise, and useful.
- Never fabricate facts, documents, or citations.
        """.strip(),
    ),
    ("human", "{input}"),
    ("placeholder", "{agent_scratchpad}"),
])


# =================================================
# REQUEST-SCOPED AGENT AND TOOLS
# =================================================

def create_request_agent(
    rag_result: dict[str, Any],
) -> AgentExecutor:
    """
    Create tools and an agent executor scoped to one chat request.

    The Private_RAG tool closes over this request's result.
    Concurrent requests therefore cannot overwrite each other's
    RAG results, and the tool does not call Domain B again.
    """
    
    def private_rag_tool(query: str) -> str:
        """Return this request's already-fetched RAG result."""
        return format_rag_result(
            query=query,
            result=rag_result,
     )

    request_tools = [
        Tool(
            name="Wikipedia",
            func=wikipedia_search,
            description=(
                "Search public Wikipedia knowledge about people, "
                "places, history, science, technology, and general "
                "facts. Use when public information is useful."
            ),
        ),
        Tool(
            name="Private_RAG",
            func=private_rag_tool,
            description=(
                "Inspect the private knowledge result retrieved "
                "for the current user's question. Use for internal "
                "documents, uploaded files, private organizational "
                "information, and stored knowledge. Returns the "
                "answer, source references, and verification status."
            ),
        ),
    ]

    request_agent = create_tool_calling_agent(
        llm=llm,
        tools=request_tools,
        prompt=prompt,
    )

    return AgentExecutor(
        agent=request_agent,
        tools=request_tools,
        verbose=True,
        return_intermediate_steps=True,
        max_iterations=4,
        max_execution_time=25,
        handle_parsing_errors=True,
    )


# =================================================
# RUN AGENT
# =================================================

def run_agent(query: str) -> dict[str, Any]:
    """Run the agent and return the existing Vue response fields."""

    if not isinstance(query, str) or not query.strip():
        return {
            "response": {
                "action": "None",
                "action_input": "",
                "observation": [],
                "final_answer": "Please enter a question.",
                "tools_used": [],
                "source": [],
                "status": "unknown",
            }
        }

    clean_query = query.strip()

    try:
        # Fetch structured RAG data once for this request.
        # private_rag.py handles its configured retries.
        rag_result = rag_search_structured(clean_query)

        # Each invocation gets its own tools and captured RAG result.
        request_executor = create_request_agent(rag_result)

        result = request_executor.invoke({
            "input": clean_query
        })

        steps = result.get("intermediate_steps", [])

        observations = []
        tools_used = []
        last_action_input = ""

        for action, observation in steps:
            tool_name = getattr(action, "tool", "None")
            tool_input = getattr(action, "tool_input", "")

            if tool_name != "None":
                tools_used.append(tool_name)

            last_action_input = tool_input

            observations.append({
                "tool": tool_name,
                "tool_input": tool_input,
                "observation": str(observation),
            })

        # Preserve tool order and remove duplicate names.
        tools_used = list(dict.fromkeys(tools_used))

        # The structured RAG result is the source of truth.
        sources = rag_result.get("source") or []

        unique_sources = []
        seen_sources = set()

        for source in sources:
            source_key = repr(source)

            if source_key not in seen_sources:
                seen_sources.add(source_key)
                unique_sources.append(source)

        rag_status = rag_result.get("status", "unknown")

        if rag_status not in {
            "sources_found",
            "unverified",
            "error",
        }:
            rag_status = "unknown"

        # The private lookup was performed even if the LLM omitted
        # the corresponding tool call from its intermediate steps.
        if "Private_RAG" not in tools_used:
            tools_used.insert(0, "Private_RAG")

        return {
            "response": {
                "action": (
                    ", ".join(tools_used)
                    if tools_used
                    else "None"
                ),
                "action_input": last_action_input,
                "observation": observations,
                "final_answer": result.get("output", ""),
                "tools_used": tools_used,
                "source": unique_sources,
                "status": rag_status,
            }
        }

    except Exception:
        logger.exception("Agent execution failed")

        return {
            "response": {
                "action": "None",
                "action_input": "",
                "observation": [
                    {
                        "tool": "Agent",
                        "observation": "Agent execution failed.",
                    }
                ],
                "final_answer": (
                    "Sorry, the agent could not complete your "
                    "request. Please try again."
                ),
                "tools_used": [],
                "source": [],
                "status": "error",
            }
        }
